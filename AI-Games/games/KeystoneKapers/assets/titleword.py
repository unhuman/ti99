CELL = 8


def rows_of(letter):
    """A glyph as exactly ROWS rows of WIDTH columns."""
    if letter not in GLYPHS:
        raise SystemExit(
            "titleword: no glyph for %r -- the title cannot draw a letter it "
            "has no art for. Add it to GLYPHS." % letter)
    rows = [r for r in GLYPHS[letter].split("\n") if r != ""]
    if len(rows) != ROWS:
        raise SystemExit("titleword: %r has %d rows, expected %d"
                         % (letter, len(rows), ROWS))
    out = []
    for r in rows:
        if len(r) > WIDTH:
            raise SystemExit("titleword: %r has a %d-column row, max %d"
                             % (letter, len(r), WIDTH))
        out.append((r + "." * WIDTH)[:WIDTH])
    return out


def check_heights():
    """One cap height for the whole face.

    The previous face ran from eleven rows to thirteen with tops and bottoms on
    different lines, which reads as letters sitting at different depths. A
    display face has ONE cap height; this asserts it rather than trusting ten
    hand-drawn grids to agree.
    """
    bad = []
    for letter in sorted(GLYPHS):
        rows = rows_of(letter)
        on = [i for i, r in enumerate(rows) if "#" in r]
        if not on:
            bad.append("%s is blank" % letter)
        elif (on[0], on[-1]) != (CAP_TOP, CAP_BOT):
            bad.append("%s occupies rows %d..%d, not %d..%d"
                       % (letter, on[0], on[-1], CAP_TOP, CAP_BOT))
    if bad:
        raise SystemExit("titleword: not one cap height:\n  "
                         + "\n  ".join(bad))


def bitmap(word):
    """The word as one image -- [row strings], letters composited at WIDTH."""
    px = [["."] * (WIDTH * len(word)) for _ in range(ROWS)]
    for i, ch in enumerate(word):
        if ch == " ":
            continue
        g = rows_of(ch)
        for y in range(ROWS):
            for x in range(WIDTH):
                if g[y][x] == "#":
                    px[y][i * WIDTH + x] = "#"
    return ["".join(r) for r in px]


def cells(word):
    """[[cell]] -- the word sliced on the character grid, row-major.

    A cell is 8 rows of 8 columns. The word is padded to whole cells; the
    padding is blank and becomes the space character.
    """
    img = bitmap(word)
    w = len(img[0])
    cw = (w + CELL - 1) // CELL
    img = [(r + "." * (cw * CELL))[:cw * CELL] for r in img]
    out = []
    for cy in range(ROWS // CELL):
        row = []
        for cx in range(cw):
            row.append([img[cy * CELL + y][cx * CELL:(cx + 1) * CELL]
                        for y in range(CELL)])
        out.append(row)
    return out


def char_bytes(cell):
    return [sum(1 << (7 - x) for x in range(CELL) if row[x] == "#")
            for row in cell]
