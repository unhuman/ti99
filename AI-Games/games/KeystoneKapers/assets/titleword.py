"""The title's name, drawn as WHOLE WORDS and sliced into characters.

WHY WORDS AND NOT LETTERS
-------------------------
The first display face gave every letter its own 2x2 block of characters, which
means every letter starts on an 8-pixel boundary. That is not typesetting, it is
a grid: the spacing cannot vary, nothing can tuck under anything else, and the
result reads as separate stamps rather than as a piece of lettering.

The reference is KERNED -- the letters are fitted to each other and drawn as one
image. So this composites the letters into a WORD bitmap at whatever advance
each pair wants, and only then slices the result on the character grid. A cell
may hold parts of two letters; that is the point.

THE BUDGET DECIDES THE WIDTH, and it is worth showing the arithmetic because it
is the whole design constraint:

    font 32..90, store art 96..181, radar canvas 208..255
      -> free: 0..31, 91..95, 182..207 = 63 codes

Three cells tall is what the name needs to look like a sign. At a 12-pixel
advance KEYSTONE is 12 cells wide and KAPERS 9, so 21 x 3 = 63 -- exactly the
budget, before any saving from blank or repeated cells. At 13 it is 69 and does
not fit at any price short of moving the store art into another bank.

So: 12-pixel advance, letters drawn up to 12 wide, tightly fitted. Condensed is
not a compromise here -- the reference's own face is tall and narrow.

DEDUPING IS NOT AN OPTIMISATION, IT IS HEADROOM. Blank cells become the space
character and identical cells share a code, which is what buys back the margin
the 63 leaves none of.
"""

