"""The title's display face -- one 16x16 letter per 2x2 block of characters.

WHY A SECOND FACE AT ALL
------------------------
The game's font is 8x8 and the title card wants the name to READ as a name, the
way the Activision original does: stacked, and much larger than everything round
it. Spacing the ordinary font out (`K E Y S T O N E`) was the cheap approximation
and it is still a small line of body text with gaps in it.

Each letter here is 16x16 -- four characters, laid out as

    TL TR        two cells across, two cells down; the display list places the
    BL BR        top row of every letter, then the bottom row

so a word is two runs in the same table format as everything else, and the
walker that draws the rest of the title draws this too. No new mechanism again.

WHERE IT LIVES. Forty characters is 320 bytes of pattern and 320 of colour, and
bank 1 had 370 free -- it does not fit. It does not need to: these are read ONCE,
by `DEFINE CHAR`/`DEFINE COLOR` at setup, exactly like the font, so they belong
in **bank 2** with it and are loaded inside the same one-and-only bank switch the
program makes. Bank 2 had 7,204 bytes spare.

THE GLYPHS are drawn on a 13-row cap height inside 16 rows, with the stems three
pixels wide, so they hold up against the marquee's lamps. Columns 13-15 are the
letter's own right-hand sidebearing -- the gap between letters is part of the
glyph rather than a separate spacing cell, which is what lets a word be one
contiguous run.
"""

