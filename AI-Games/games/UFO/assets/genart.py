def rows(art):
    return [ln for ln in art.strip("\n").split("\n") if ln.strip("\n")]


def bits(line, lo, hi):
    v = 0
    for i in range(lo, hi):
        c = line[i] if i < len(line) else "."
        v = (v << 1) | (0 if c == "." else 1)
    return v


def sprite_bytes(art):
    """32 bytes: 16 rows of the left half, then 16 rows of the right half."""
    r = rows(art)
    assert len(r) == 16, (len(r), r[:2])
    return [bits(ln, 0, 8) for ln in r] + [bits(ln, 8, 16) for ln in r]


def grid_bytes(g):
    """The same quadrant order, from a computed 16x16 grid."""
    def pack(row, lo, hi):
        v = 0
        for i in range(lo, hi):
            v = (v << 1) | row[i]
        return v
    return [pack(r, 0, 8) for r in g] + [pack(r, 8, 16) for r in g]


def char_bytes(art):
    r = rows(art)
    assert len(r) == 8, len(r)
    return [bits(ln, 0, 8) for ln in r]


def emit(fh, label, data, comment):
    fh.write("%s:\t' %s\n" % (label, comment))
    if len(data) % 2:
        data = data + [0]
    for i in range(0, len(data), 8):
        fh.write("\tDATA BYTE " + ",".join("$%02X" % b for b in data[i:i + 8]) + "\n")
    fh.write("\n")


def preview(g):
    return "\n".join("".join("#" if v else "." for v in row) for row in g)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "art.bas")

    with open(out, "w", newline="\n") as fh:
        fh.write("""\t' UFO! art -- GENERATED by assets/genart.py. Do not edit; regenerate.
\t'
\t' Sprites are QUADRANT-ORDERED for the TMS9918: 16 rows of the left half then
\t' 16 rows of the right half.
\t'
\t' Every block is an EVEN number of bytes -- an odd DATA BYTE run leaves the
\t' location counter odd and silently misaligns every word table after it
\t' (CLAUDE.md 3A).

""")
        emit(fh, "spr_ship", sprite_bytes(SHIP),
             "the cruiser -- 6x6, small so the force field owns the cell")

        data = []
        for p in range(N_PHASE):
            data += grid_bytes(ring_grid(p))
        emit(fh, "spr_ring", data,
             "force field, %d rotation phases -- COMPUTED, see genart.py" % N_PHASE)

        emit(fh, "spr_gundot", sprite_bytes(GUNDOT),
             "the aiming dot -- always centred; direction lives in the offset table")

        emit(fh, "spr_sat", sprite_bytes(SAT_PLUS) + sprite_bytes(SAT_CROSS),
             "satellite: PLUS then CROSS -- the original's own fake-rotation trick")

        emit(fh, "spr_ufo", sprite_bytes(UFO_A) + sprite_bytes(UFO_B),
             "Light-speed Starship, 2 frames")

        emit(fh, "spr_laser", sprite_bytes(LASER), "player laser bolt")
        emit(fh, "spr_missile", sprite_bytes(MISSILE), "enemy missile -- smaller than the bolt")

        emit(fh, "spr_boom", sprite_bytes(BOOM_A) + sprite_bytes(BOOM_B) + sprite_bytes(BOOM_C),
             "explosion, 3 frames -- shared by every death")

        emit(fh, "chr_stars", char_bytes(STAR_S) + char_bytes(STAR_M) + char_bytes(STAR_L),
             "starfield: small, medium, large -- static characters, free per frame")

        emit(fh, "chr_life", char_bytes(LIFE_CH),
             "spare-ship icon for the HUD -- SPARES, excluding the one being flown")

    print("wrote %s" % os.path.normpath(out))
    print()
    ship = rows(SHIP)
    grids = [ring_grid(p) for p in range(N_PHASE)]
    print("force field, all %d phases (ship overlaid as 'o'):" % N_PHASE)
    for y in range(16):
        cols = []
        for g in grids:
            line = ""
            for x in range(16):
                if g[y][x]:
                    line += "#"
                elif ship[y][x] != ".":
                    line += "o"
                else:
                    line += "."
            cols.append(line)
        print("   " + "   ".join(cols))
    same = [p for p in range(N_PHASE) if grids[p] == grids[(p + 1) % N_PHASE]]
    print()
    print("identical adjacent phases: %s" % (same if same else "none -- good"))


if __name__ == "__main__":
    main()
