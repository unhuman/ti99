#!/usr/bin/env python3
"""UFO! art generator -- art in, src/art.bas out.

Sprites are 16x16 and the TMS9918 stores them QUADRANT-ORDERED: all 16 rows of
the LEFT half, then all 16 rows of the RIGHT half. Reading a 16-wide bitmap as
32 sequential rows produces garbage that still assembles, so the art lives here
in readable form and this file does the interleave once, correctly.

Two kinds of art live here, deliberately:

  * SHAPES are ASCII, because a saucer or a plus sign is something you draw.
  * THE FORCE-FIELD RING IS COMPUTED, because it is eight dots on a circle at
    four rotation phases -- thirty-two positions that have to stay evenly
    spaced and concentric. Placed by eye they wobble, and a wobbling ring reads
    as a rendering bug rather than as a shimmer.

Every emitted DATA BYTE block is padded to an EVEN length: an odd-length byte
run leaves the assembler's location counter odd and silently misaligns every
word table after it (CLAUDE.md 3A).

Run:  python3 genart.py      writes ../src/art.bas
"""

import math
import os

# ------------------------------------------------------------------ geometry
#
# All of these are in 16x16 sprite-cell pixels, measured from the cell's
# top-left, with the cell centre at (7.5, 7.5).
#
# The three radii are chosen so nothing ever merges into anything else:
#
#   ship        6x6 blob, x and y spanning 5..10
#   INNER dots  r = 4.6 -- at 90 deg that is x 12, clear of the ship's max x 10
#   OUTER ring  r = 6.8 -- at 90 deg that is x 14, two cells clear of the inner
#
# Squeezing these was tried and does not work: at r = 5.0 / 6.3 the inner and
# outer dots land on ADJACENT cells at the compass points and merge into a
# 4-px dash exactly four times per revolution, which looks like a glitch.
R_OUTER = 6.8
R_INNER = 4.6
CENTRE = 7.5

# Eight main dots, and the phase step is 45/4 deg so four phases carry the ring
# through exactly one dot position -- the animation is then seamless in both
# directions and cannot drift.
N_DOTS = 8
N_PHASE = 4

# The "two rapidly circling dots" (Gaming After 40's description of the real
# thing). They orbit at 90 deg per phase against the outer ring's 11.25, so
# they visibly race around inside it -- which is the whole point of them.
N_FAST = 2


def blank():
    return [[0] * 16 for _ in range(16)]


def dot(grid, cx, cy):
    """A 2x2 dot centred as near (cx, cy) as the pixel grid allows.

    1x1 would be more accurate and is invisible at this size; 3x3 merges with
    its neighbours at r = 4.6. 2x2 is the only size that reads as a dot.
    """
    x = int(round(cx - 0.5))
    y = int(round(cy - 0.5))
    for dy in range(2):
        for dx in range(2):
            px, py = x + dx, y + dy
            if 0 <= px < 16 and 0 <= py < 16:
                grid[py][px] = 1


def ring_grid(phase):
    g = blank()
    base = phase * (360.0 / N_DOTS / N_PHASE)      # 11.25 deg per phase
    for k in range(N_DOTS):
        a = math.radians(base + k * (360.0 / N_DOTS))
        dot(g, CENTRE + R_OUTER * math.sin(a), CENTRE - R_OUTER * math.cos(a))
    # +45 so a fast dot NEVER lines up radially with an outer dot. Without it,
    # phase 0 puts both on the vertical axis and the ring reads as a bar with
    # blobs on it rather than as a circle.
    fast = 45.0 + phase * (360.0 / N_PHASE)        # 90 deg per phase
    for k in range(N_FAST):
        a = math.radians(fast + k * (360.0 / N_FAST))
        dot(g, CENTRE + R_INNER * math.sin(a), CENTRE - R_INNER * math.cos(a))
    return g


