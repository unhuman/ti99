#!/usr/bin/env python3
"""JOUST art generator -- ASCII art in, src/art.bas out.

Sprites are 16x16 and the TMS9918 stores them QUADRANT-ORDERED: all 16 rows of
the LEFT half, then all 16 rows of the RIGHT half. Reading a 16-wide bitmap as
32 sequential rows produces garbage that still assembles, so the art lives here
as readable ASCII and this file does the interleave once, correctly.

Characters are 8x8, eight bytes each, straightforward.

Every emitted DATA BYTE block is padded to an EVEN length: an odd-length byte run
leaves the assembler's location counter odd and silently misaligns every word
table after it (TRUNCATION.md 1d).

Run:  python3 genart.py      writes ../src/art.bas
"""

