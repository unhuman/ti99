def rows(art):
    r = [ln for ln in art.strip("\n").split("\n") if ln.strip("\n")]
    return r


def bits(line, lo, hi):
    v = 0
    for i in range(lo, hi):
        c = line[i] if i < len(line) else "."
        v = (v << 1) | (0 if c == "." else 1)
    return v


def mirror8(b):
    out = 0
    for i in range(8):
        out = (out << 1) | ((b >> i) & 1)
    return out


def sprite_bytes(art, flip=False):
    """32 bytes: 16 rows of the left half, then 16 rows of the right half."""
    r = rows(art)
    assert len(r) == 16, len(r)
    left = [bits(ln, 0, 8) for ln in r]
    right = [bits(ln, 8, 16) for ln in r]
    if flip:
        left, right = [mirror8(b) for b in right], [mirror8(b) for b in left]
    return left + right


def char_bytes(art):
    r = rows(art)
    assert len(r) == 8, len(r)
    return [bits(ln, 0, 8) for ln in r]


def emit(fh, label, data, comment):
    fh.write("%s:\t' %s\n" % (label, comment))
    if len(data) % 2:
        data = data + [0]
    for i in range(0, len(data), 8):
        fh.write("\tDATA BYTE " + ",".join("$%02X" % b for b in data[i:i + 8]) + "\n")
    fh.write("\n")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "art.bas")
    with open(out, "w", newline="\n") as fh:
        fh.write("""\t' JOUST art -- GENERATED by assets/genart.py. Do not edit; regenerate.
\t'
\t' Sprites are QUADRANT-ORDERED for the TMS9918: 16 rows of the left half then
\t' 16 rows of the right half. Each mount is stored twice, facing right and facing
\t' left, because the VDP cannot mirror a sprite.
\t'
\t' Every block is an EVEN number of bytes -- an odd DATA BYTE run misaligns every
\t' word table after it (TRUNCATION.md 1d).

""")
        # player: 4 frames right, 4 frames left = 8 sprites = patterns 0..31
        data = []
        for k in ("up", "mid", "down", "skid"):
            data += sprite_bytes(PLAYER[k])
        emit(fh, "spr_mount_r", data, "ostrich/buzzard facing RIGHT: up, mid, down, skid")

        data = []
        for k in ("up", "mid", "down", "skid"):
            data += sprite_bytes(PLAYER[k], flip=True)
        emit(fh, "spr_mount_l", data, "the same four, facing LEFT")

        emit(fh, "spr_egg", sprite_bytes(EGG), "egg")
        emit(fh, "spr_runner", sprite_bytes(RUNNER), "unhorsed knight, on foot")

        for name in ("plat_l", "plat_m", "plat_r", "lava_a", "lava_b", "lava_c", "life"):
            emit(fh, "chr_" + name, char_bytes(CHARS[name]), name)

    n = os.path.getsize(out)
    print("wrote %s (%d bytes)" % (os.path.normpath(out), n))


if __name__ == "__main__":
    main()
