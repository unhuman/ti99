def compose(*layers):
    """Overlay canvas layers into one 16x20 figure. A 5-row layer is legs and
    sits on the bottom rows; anything else starts at the top. Overlap fails."""
    out = []
    for y in range(20):
        row = ["."] * 16
        for layer in layers:
            rr = [r for r in layer.strip("\n").split("\n")]
            off = 20 - len(rr) if len(rr) == 5 else 0
            if off <= y < off + len(rr):
                for x, c in enumerate(rr[y - off]):
                    if c != ".":
                        if row[x] not in (".", c):
                            raise SystemExit("genart: rider and mount overlap at row %d col %d" % (y, x))
                        row[x] = c
        out.append("".join(row))
    return out


def layer(fig, ch, top):
    """One sprite's 16 rows out of a composed figure: pixels marked ch only."""
    return "\n".join("".join("X" if c == ch else "." for c in fig[r]) for r in range(top, top + 16))


MOUNT_FRAMES = ("stand", "run1", "run2", "run3", "run4", "skid", "up", "down")


def figures(body, legs, wup, wdn):
    out = []
    for f in MOUNT_FRAMES:
        if f == "up":
            out.append(compose(RIDER, body, legs["tuck"], wup))
        elif f == "down":
            out.append(compose(RIDER, body, legs["tuck"], wdn))
        else:
            out.append(compose(RIDER, body, legs[f]))
    return out


