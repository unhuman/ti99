# Five rows; map row 0 appears at screen row 17. Camps are 48 pixels wide.
MAP = [[32]*160 for _ in range(5)]
MAP[4] = [128]*160
for c in range(160):
    phase = c % 18
    if phase in (0,1,2,3):
        MAP[2][c] = 130 if phase < 2 else 131
        MAP[3][c] = 132
for camp in (16,48,80,112):
    for c in range(camp-3, camp+3):
        MAP[1][c] = 134
        MAP[2][c] = 133
        MAP[3][c] = 133
    MAP[2][camp] = 135; MAP[3][camp] = 135
for c in range(142,147):
    MAP[0][c] = 134
    MAP[1][c] = 133
    MAP[2][c] = 133
    MAP[3][c] = 133
MAP[2][144] = 136; MAP[3][144] = 136
for c in range(148,156): MAP[4][c] = 137
MAP[4][151] = 138
for y in range(5): MAP[y][134] = 139

def emit(label, data):
    assert len(data) % 2 == 0, label
    return label + ':\n' + ''.join('    DATA BYTE '+','.join(str(v) for v in data[i:i+16])+'\n' for i in range(0,len(data),16))

def generate():
    text = "' Generated by assets/generate.py; edit the generator.\n"
    text += emit('sprite_art', [b for a in SPRITES for b in sprite_bytes(a)])
    text += emit('tile_art', [b for bits,_ in TILES for b in bits])
    text += emit('tile_colors', [c for _,c in TILES for _ in range(8)])
    text += emit('world_map', [c for r in MAP for c in r])
    text += emit('ground_row', [129]*32)
    (ROOT/'src/assets.bas').write_text(text, encoding='utf-8', newline='\n')
    print(f'Assets: {len(SPRITES)} sprites, {len(TILES)} tiles, {len(MAP)*160} map bytes')

if __name__ == '__main__': generate()
